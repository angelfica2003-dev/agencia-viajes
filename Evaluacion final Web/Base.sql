--Creando una base de datos llamada "Libros" en oracle

    CREATE TABLE Usuario (
        id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre VARCHAR2(100) NOT NULL,
        correo_electronico VARCHAR2(100) UNIQUE NOT NULL,
        contrasena VARCHAR2(255) NOT NULL,
        direccion VARCHAR2(255) NOT NULL,
        telefono VARCHAR2(20) NOT NULL,
        rol VARCHAR2(20) DEFAULT 'cliente' NOT NULL,
        CONSTRAINT chk_usuario_rol CHECK (rol IN ('cliente', 'admin'))
    );
create table libros (
    id_libro INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR2(255) NOT NULL,
    autor VARCHAR2(100) NOT NULL,
    precio DECIMAL(10, 2) NOT NULL,
    stock INT NOT NULL
);

create table carrito (
    id_carrito INT PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_libro INT NOT NULL,
    cantidad INT NOT NULL,
    total DECIMAL(10, 2) NOT NULL,
    FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario),
    FOREIGN KEY (id_libro) REFERENCES libros(id_libro)
);

