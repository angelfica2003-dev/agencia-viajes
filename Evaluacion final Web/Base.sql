CREATE DATABASE IF NOT EXISTS LIBRERIA
    CHARACTER SET utf8mb4
        COLLATE utf8mb4_spanish_ci;

USE LIBRERIA;

CREATE TABLE IF NOT EXISTS USUARIOS (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(254) NOT NULL,
    CONTRASENA VARCHAR(255) NOT NULL,
    DIRECCION VARCHAR(255) NOT NULL,
    TELEFONO VARCHAR(30) NOT NULL,
    ROL ENUM('cliente', 'admin') NOT NULL DEFAULT 'cliente',
    PRIMARY KEY (ID),
    UNIQUE KEY uq_usuarios_email (EMAIL)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS LIBROS (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    TITULO VARCHAR(255) NOT NULL,
    AUTOR VARCHAR(100) NOT NULL,
    PRECIO DECIMAL(10, 2) NOT NULL,
    CANTIDAD_INVENTARIO INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    CONSTRAINT chk_libros_precio CHECK (PRECIO > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CARRITO (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    ID_USUARIO BIGINT UNSIGNED NOT NULL,
    ID_LIBRO BIGINT UNSIGNED NOT NULL,
    CANTIDAD INT UNSIGNED NOT NULL,
    MONTO_TOTAL DECIMAL(12, 2) NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY uq_carrito_usuario_libro (ID_USUARIO, ID_LIBRO),
    CONSTRAINT fk_carrito_usuario FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID) ON DELETE CASCADE,
    CONSTRAINT fk_carrito_libro FOREIGN KEY (ID_LIBRO)
        REFERENCES LIBROS (ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PEDIDOS (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    ID_USUARIO BIGINT UNSIGNED NOT NULL,
    DIRECCION_ENVIO VARCHAR(255) NOT NULL,
    MONTO_TOTAL DECIMAL(12, 2) NOT NULL,
    ESTADO ENUM('Pendiente', 'Preparando', 'Enviado', 'Entregado', 'Cancelado')
        NOT NULL DEFAULT 'Pendiente',
    FECHA_CREACION TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID),
    KEY ix_pedidos_usuario_fecha (ID_USUARIO, FECHA_CREACION),
    CONSTRAINT fk_pedidos_usuario FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DETALLE_PEDIDO (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    ID_PEDIDO BIGINT UNSIGNED NOT NULL,
    ID_LIBRO BIGINT UNSIGNED NOT NULL,
    TITULO_LIBRO VARCHAR(255) NOT NULL,
    PRECIO_UNITARIO DECIMAL(10, 2) NOT NULL,
    CANTIDAD INT UNSIGNED NOT NULL,
    SUBTOTAL DECIMAL(12, 2) NOT NULL,
    PRIMARY KEY (ID),
    KEY ix_detalle_pedido_pedido (ID_PEDIDO),
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (ID_PEDIDO)
        REFERENCES PEDIDOS (ID) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_libro FOREIGN KEY (ID_LIBRO)
        REFERENCES LIBROS (ID)
) ENGINE=InnoDB;

